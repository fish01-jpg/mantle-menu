#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const score = JSON.parse(read('intro/sequence.json'));
const html = '<!-- Generated by scripts/build-sp1der-intro.cjs. Edit intro/ sources. -->\n' +
  read('intro/shell.html')
    .replace('/*__STYLE__*/', () => read('intro/sp1der-intro.css'))
    .replace('/*__SCORE__*/', () => 'window.SP1DER_INTRO_SCORE = ' + JSON.stringify(score) + ';')
    .replace('/*__SCRIPT__*/', () => read('intro/sp1der-intro.js'));
const target = path.join(root, 'sp1der-intro.html');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== html) {
    console.error('sp1der-intro.html needs rebuilding'); process.exitCode = 1;
  } else console.log('Intro beta generated entry is current.');
} else { fs.writeFileSync(target, html); console.log('Built sp1der-intro.html'); }
